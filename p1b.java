public class p1b {
    public static void main(String[] args) {
        int x = 5, y = 10;

        System.out.println("x + y = "+ (x + y));
        System.out.println("x - y = "+ (x - y));
        System.out.println("x * y = "+ (x * y));
        System.out.println("x / y = "+ (x / y));
        System.out.println("x > y = "+ (x > y));

        boolean v = true, w = false;

        System.out.println("v && w = "+ (v && w));
        
        x += 5;
        System.out.println("x += 5 = "+ x);
    }
}